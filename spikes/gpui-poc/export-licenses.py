"""Export resolved dependency declarations, not a substitute for a license audit."""
import argparse
import json
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--features", default="", help="Explicit Cargo feature list for this audit")
parser.add_argument("--output", type=Path, default=root / "research" / "dependency-licenses.md")
args = parser.parse_args()
command = ["cargo", "metadata", "--locked", "--format-version", "1", "--manifest-path",
           str(root / "Cargo.toml")]
if args.features:
    command.extend(["--features", args.features])
result = subprocess.run(
    command, capture_output=True, text=True, encoding="utf-8", check=True,
)
metadata = json.loads(result.stdout)
rows = ["# Resolved dependency license declarations", "",
        "Generated by `python spikes/gpui-poc/export-licenses.py` using locked Cargo metadata.",
        "Includes resolved target-specific dependencies; declarations require source/resource review.",
        f"Explicit features: `{args.features or 'workspace defaults'}`.",
        "", "| Package | Version | Declared license | Source |",
        "|---|---|---|---|"]
for package in sorted(metadata["packages"], key=lambda p: (p["name"], p["version"])):
    license_text = package.get("license") or "UNDECLARED (manual review required)"
    source = package.get("source") or "workspace"
    rows.append(f"| {package['name']} | {package['version']} | {license_text} | {source} |")
destination = args.output
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text("\n".join(rows) + "\n", encoding="utf-8")
print(f"Exported {len(metadata['packages'])} package declarations to {destination}")
