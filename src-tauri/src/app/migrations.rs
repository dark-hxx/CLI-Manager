// 保留宿主入口，只将中立迁移定义转换为 SQL 插件类型。
pub(crate) fn migrations() -> Vec<Migration> {
    cli_manager_core_db::migrations::migrations()
        .into_iter()
        .map(|migration| Migration {
            version: migration.version,
            description: migration.description,
            sql: migration.sql,
            kind: MigrationKind::Up,
        })
        .collect()
}

#[cfg(test)]
#[test]
fn plugin_adapter_preserves_historical_migration_checksums() {
    use sha2::{Digest, Sha384};
    let actual: Vec<_> = migrations()
        .into_iter()
        .map(|migration| {
            assert!(matches!(migration.kind, MigrationKind::Up));
            serde_json::json!({
                "version": migration.version,
                "description": migration.description,
                "sha384": format!("{:x}", Sha384::digest(migration.sql.as_bytes())),
            })
        })
        .collect();
    let expected: serde_json::Value =
        serde_json::from_str(include_str!("../../tests/snapshots/main-migrations.json")).unwrap();
    assert_eq!(serde_json::json!(actual), expected);
}
